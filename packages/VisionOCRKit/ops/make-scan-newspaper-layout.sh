#!/usr/bin/env bash
# make-scan-newspaper-layout.sh — the scanned-newspaper detector's download and its vendored layout processing
# (W47.wh-yolo-scans): newspaper-ocr's DocLayout-YOLO route, which W46.ocr-regions measured on the 15 L9 scans.
#
#   make-scan-newspaper-layout.sh VENV_PYTHON WORKDIR
#
# VENV_PYTHON has torch 2.7.0, torchvision 0.22.0, coremltools 9.0, doclayout-yolo 0.0.4, dill and huggingface-hub.
# WORKDIR gets newspaper-ocr's checkout at the measured commit, the pinned checkpoint, the Core ML package and
#   WORKDIR/doclayout-yolo-1280.tgz   the download (`ModelDownloads.Item.scanNewspaperLayout`), its size and sha256
#                                     printed for the plan; published to the models-1 release by the owner
# and regenerates Sources/VisionOCRKit/Resources/npo_layout.py, newspaper-ocr's `models.py` and
# `layout_processor.py` joined into one module (MIT; the licence is Resources/newspaper-ocr-LICENSE), changed only
# by dropping the package import and the second `from __future__` line. The app runs it in the shared runtime.
set -euo pipefail
PY="$1"; WORK="$2"
HERE="$(cd "$(dirname "$0")" && pwd)"
RES="$HERE/../Sources/VisionOCRKit/Resources"
NPO_COMMIT=1d5c878            # the newspaper-ocr commit W46.ocr-regions measured (setup-layout.sh), version 0.11.0
REPO=juliozhao/DocLayout-YOLO-DocStructBench-imgsz1280-2501
REV=2ea5c2bf47cc69eb4eeb5b8eabb6c6c333490f78
mkdir -p "$WORK"; cd "$WORK"

[ -d npo ] || git clone -q https://github.com/nealcaren/newspaper-ocr.git npo
git -C npo checkout -q "$NPO_COMMIT"
SRC=npo/src/newspaper_ocr
{
  echo '# npo_layout.py — newspaper-ocr 0.11.0 (commit '"$NPO_COMMIT"', MIT, Copyright (c) 2025 Neal Caren; the licence is'
  echo '# newspaper-ocr-LICENSE beside this file): models.py and layout_processor.py joined. Generated by'
  echo '# packages/VisionOCRKit/ops/make-scan-newspaper-layout.sh; do not edit. W47.wh-yolo-scans.'
  echo 'from __future__ import annotations'
  grep -v '^from __future__ import annotations$' "$SRC/models.py"
  grep -v -e '^from __future__ import annotations$' -e '^from newspaper_ocr.models import' "$SRC/layout_processor.py"
} > "$RES/npo_layout.py"
cp npo/LICENSE "$RES/newspaper-ocr-LICENSE"

W=$("$PY" -c "from huggingface_hub import hf_hub_download as d; print(d('$REPO', 'doclayout_yolo_docstructbench_imgsz1280_2501.pt', revision='$REV', cache_dir='hub'))")
rm -rf scan-layout.mlpackage compiled
"$PY" "$HERE/convert-scan-layout.py" "$W" scan-layout.mlpackage
mkdir compiled
xcrun coremlcompiler compile scan-layout.mlpackage compiled >/dev/null
mv compiled/scan-layout.mlmodelc compiled/doclayout-yolo-1280.mlmodelc
# The archive holds the one folder `ModelDownloads.install` expects (`top`). The pinned hash is of this build's file,
# which is the one published: a rebuild gives new bytes (times), so it is re-pinned.
COPYFILE_DISABLE=1 tar --no-mac-metadata -C compiled -czf doclayout-yolo-1280.tgz doclayout-yolo-1280.mlmodelc
echo "doclayout-yolo-1280.tgz $(stat -f %z doclayout-yolo-1280.tgz) bytes, sha256 $(shasum -a 256 doclayout-yolo-1280.tgz | cut -d' ' -f1)"
